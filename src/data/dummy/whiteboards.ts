import type { Stroke, Whiteboard } from "@/types";

function pen(id: string, color: string, width: number, points: [number, number][], tool: Stroke["tool"] = "pen"): Stroke {
  return { id, tool, color, width, points: points.map(([x, y]) => ({ x, y })) };
}

function text(id: string, color: string, x: number, y: number, value: string): Stroke {
  return { id, tool: "text", color, width: 2, points: [{ x, y }], text: value };
}

function board(
  partial: Omit<Whiteboard, "pages" | "background"> & {
    background?: Whiteboard["background"];
    strokes?: Stroke[];
  },
): Whiteboard {
  const { strokes = [], background = "grid", ...rest } = partial;
  return {
    ...rest,
    background,
    pages: [{ id: `${rest.id}-page-1`, strokes }],
  };
}

