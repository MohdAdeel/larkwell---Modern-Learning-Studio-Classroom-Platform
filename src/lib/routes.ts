export function homeForRole(role: "guest" | "student" | "teacher" | "admin") {
  if (role === "student") return routes.student.dashboard;
  if (role === "teacher") return routes.teacher.dashboard;
  if (role === "admin") return routes.admin.dashboard;
  return routes.signIn;
}
